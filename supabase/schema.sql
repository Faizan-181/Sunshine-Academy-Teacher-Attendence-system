-- A teacher checks in. The date and time come from the DATABASE clock (academy timezone), never from the browser.
create or replace function public.self_check_in() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_tid bigint := private.current_teacher_id();
  v_now timestamp := private.academy_now();
  v_today date := v_now::date;
  v_time time := date_trunc('minute', v_now)::time;
  v_ex public.attendance; v_status text; v_row public.attendance; v_t public.teachers;
begin
  if (select auth.uid()) is null then perform private.fail(401, 'Please sign in to continue.'); end if;
  if v_tid is null then perform private.fail(403, 'Your account is not active.'); end if;
  if private.setting('self_checkin', '1') <> '1' then
    perform private.fail(403, 'Self check-in is turned off. Please ask the administrator to mark your attendance.');
  end if;
  select * into v_ex from public.attendance where teacher_id = v_tid and attendance_date = v_today;
  if found then
    perform private.fail(409, case when v_ex.check_in is not null then 'You have already checked in today.'
                                   else 'Your attendance for today has already been marked by the administrator.' end);
  end if;
  v_status := case when private.minutes_of(v_time) > private.on_time_limit() then 'late' else 'present' end;
  begin
    insert into public.attendance (teacher_id, attendance_date, check_in, status, remarks)
    values (v_tid, v_today, v_time, v_status, 'Self check-in') returning * into v_row;
  exception when unique_violation then
    perform private.fail(409, 'You have already checked in today.');
  end;
  select * into v_t from public.teachers where id = v_tid;
  return jsonb_build_object(
    'message', case when v_status = 'late'
        then format('Checked in at %s. You are marked Late (%s minutes after %s).', to_char(v_time, 'FMHH12:MI AM'), v_row.late_minutes, to_char(private.setting('school_start', '08:00')::time, 'FMHH12:MI AM'))
        else format('Checked in at %s. You are marked Present.', to_char(v_time, 'FMHH12:MI AM')) end,
    'data', private.att_json(v_row, v_t));
end $$;

create or replace function public.self_check_out() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_tid bigint := private.current_teacher_id();
  v_now timestamp := private.academy_now();
  v_time time := date_trunc('minute', v_now)::time;
  v_rec public.attendance; v_t public.teachers;
begin
  if (select auth.uid()) is null then perform private.fail(401, 'Please sign in to continue.'); end if;
  if v_tid is null then perform private.fail(403, 'Your account is not active.'); end if;
  if private.setting('self_checkin', '1') <> '1' then
    perform private.fail(403, 'Self check-in is turned off. Please ask the administrator to mark your attendance.');
  end if;
  select * into v_rec from public.attendance where teacher_id = v_tid and attendance_date = v_now::date for update;
  if not found then perform private.fail(409, 'Please check in first.'); end if;
  if v_rec.status in ('absent', 'leave') then perform private.fail(409, 'Your attendance for today was marked by the administrator.'); end if;
  if v_rec.check_in is null then perform private.fail(409, 'Please check in first.'); end if;
  if v_rec.check_out is not null then perform private.fail(409, 'You have already checked out today.'); end if;
  if v_time <= v_rec.check_in then perform private.fail(409, 'Please wait a minute before checking out.'); end if;
  update public.attendance set check_out = v_time where id = v_rec.id returning * into v_rec;
  select * into v_t from public.teachers where id = v_tid;
  return jsonb_build_object('message', 'Checked out at ' || to_char(v_time, 'FMHH12:MI AM') || '. Have a good day!', 'data', private.att_json(v_rec, v_t));
end $$;

-- Clean "HH:MM" text -> time (empty -> NULL). Raises a friendly error otherwise.
create or replace function private.parse_time(p_text text, p_hint text) returns time
language plpgsql immutable set search_path = '' as $$
begin
  if coalesce(trim(p_text), '') = '' then return null; end if;
  if trim(p_text) !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' then perform private.fail(400, 'Enter the time as HH:MM.', p_hint); end if;
  return trim(p_text)::time;
end $$;

-- Admin saves many records for one date. Re-saving never duplicates (unique teacher + date).
create or replace function public.admin_save_attendance(p_date date, p_records jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_rec jsonb; v_i integer := 0; v_saved integer := 0;
  v_tid bigint; v_status text; v_in time; v_out time; v_remarks text;
  v_old public.attendance; v_new public.attendance; v_uid uuid := (select auth.uid());
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  if p_date is null then perform private.fail(400, 'Enter a valid date.', 'date'); end if;
  if p_date > private.academy_today() then perform private.fail(400, 'You cannot mark attendance for a future date.', 'date'); end if;
  if p_records is null or jsonb_typeof(p_records) <> 'array' or jsonb_array_length(p_records) = 0 or jsonb_array_length(p_records) > 500 then
    perform private.fail(400, 'There are no teachers to save.');
  end if;

  for v_rec in select * from jsonb_array_elements(p_records) loop
    begin v_tid := (v_rec ->> 'teacher')::bigint; exception when others then v_tid := null; end;
    v_status := v_rec ->> 'status';
    if v_tid is null then perform private.fail(400, 'Invalid teacher.'); end if;
    if v_status is null or v_status not in ('present', 'absent', 'late', 'leave') then perform private.fail(400, 'Choose a status.', 'records.' || v_i || '.status'); end if;
    v_remarks := left(trim(coalesce(v_rec ->> 'remarks', '')), 201);
    if char_length(v_remarks) > 200 then perform private.fail(400, 'Remarks are too long (200 characters max).', 'records.' || v_i || '.remarks'); end if;
    v_in  := private.parse_time(v_rec ->> 'check_in',  'records.' || v_i || '.check_in');
    v_out := private.parse_time(v_rec ->> 'check_out', 'records.' || v_i || '.check_out');
    if v_status in ('absent', 'leave') then v_in := null; v_out := null; end if;
    if v_in is not null and v_out is not null and v_out <= v_in then perform private.fail(400, 'Check-out must be after check-in.', 'records.' || v_i || '.check_out'); end if;
    if not exists (select 1 from public.teachers t where t.id = v_tid and t.status = 'active') then
      perform private.fail(400, 'Some teachers could not be found or are inactive. Please refresh and try again.');
    end if;

    select * into v_old from public.attendance where teacher_id = v_tid and attendance_date = p_date for update;
    if not found then
      insert into public.attendance (teacher_id, attendance_date, check_in, check_out, status, remarks, created_by, updated_by)
      values (v_tid, p_date, v_in, v_out, v_status, v_remarks, v_uid, v_uid) returning * into v_new;
      perform private.audit(v_uid, 'attendance_created', 'attendance', v_new.id::text, null,
        jsonb_build_object('teacher_id', v_tid, 'date', p_date, 'status', v_status, 'check_in', v_in, 'check_out', v_out, 'remarks', v_remarks));
    elsif (v_old.status, v_old.check_in, v_old.check_out, v_old.remarks) is distinct from (v_status, v_in, v_out, v_remarks) then
      update public.attendance set status = v_status, check_in = v_in, check_out = v_out, remarks = v_remarks, updated_by = v_uid
       where id = v_old.id returning * into v_new;
      perform private.audit(v_uid, 'attendance_edited', 'attendance', v_new.id::text,
        jsonb_build_object('status', v_old.status, 'check_in', v_old.check_in, 'check_out', v_old.check_out, 'remarks', v_old.remarks),
        jsonb_build_object('status', v_status, 'check_in', v_in, 'check_out', v_out, 'remarks', v_remarks));
    end if;
    v_saved := v_saved + 1; v_i := v_i + 1;
  end loop;
  return jsonb_build_object('message', 'Attendance saved successfully.', 'saved', v_saved);
end $$;

-- Admin corrects one record (teacher and date cannot change).
create or replace function public.admin_update_attendance(p_id bigint, p_status text, p_check_in text, p_check_out text, p_remarks text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_old public.attendance; v_new public.attendance; v_t public.teachers; v_uid uuid := (select auth.uid());
  v_in time; v_out time; v_remarks text := trim(coalesce(p_remarks, ''));
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  if p_status is null or p_status not in ('present', 'absent', 'late', 'leave') then perform private.fail(400, 'Choose a status.', 'status'); end if;
  if char_length(v_remarks) > 200 then perform private.fail(400, 'Remarks are too long (200 characters max).', 'remarks'); end if;
  v_in := private.parse_time(p_check_in, 'check_in'); v_out := private.parse_time(p_check_out, 'check_out');
  if p_status in ('absent', 'leave') then v_in := null; v_out := null; end if;
  if v_in is not null and v_out is not null and v_out <= v_in then perform private.fail(400, 'Check-out must be after check-in.', 'check_out'); end if;
  select * into v_old from public.attendance where id = p_id for update;
  if not found then perform private.fail(404, 'We could not find that attendance record.'); end if;
  update public.attendance set status = p_status, check_in = v_in, check_out = v_out, remarks = v_remarks, updated_by = v_uid
   where id = p_id returning * into v_new;
  if (v_old.status, v_old.check_in, v_old.check_out, v_old.remarks) is distinct from (v_new.status, v_new.check_in, v_new.check_out, v_new.remarks) then
    perform private.audit(v_uid, 'attendance_edited', 'attendance', p_id::text,
      jsonb_build_object('status', v_old.status, 'check_in', v_old.check_in, 'check_out', v_old.check_out, 'remarks', v_old.remarks),
      jsonb_build_object('status', v_new.status, 'check_in', v_new.check_in, 'check_out', v_new.check_out, 'remarks', v_new.remarks));
  end if;
  select * into v_t from public.teachers where id = v_new.teacher_id;
  return jsonb_build_object('message', 'Attendance updated successfully.', 'data', private.att_json(v_new, v_t));
end $$;

