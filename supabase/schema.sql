-- =====================================================================================
-- Sunshine Academy — Teachers Attendance System
-- Supabase / PostgreSQL schema, security (RLS) and server-side logic
--
-- HOW TO USE: Supabase Dashboard -> SQL Editor -> New query -> paste this WHOLE file -> Run.
-- It is safe to run again (it uses "create if not exists" / "create or replace" / "drop ... if exists").
-- It never deletes any attendance data.
--
-- SECURITY MODEL (read this once):
--   * Row Level Security (RLS) is ON for every table. Browsers can only SELECT, and only the rows
--     their role may see (teacher = own rows only, admin = everything).
--   * Browsers have NO insert/update/delete privilege on any table. Every change goes through a
--     function below that checks "is this an active admin?" (or "is this the signed-in teacher?")
--     inside the database. Role and status are looked up live from the database on every call,
--     never taken from the browser or from user-editable token fields.
--   * Attendance has no delete function and no delete policy: history is permanent.
-- =====================================================================================

-- ---------- 0. Schemas ----------------------------------------------------------------
create schema if not exists private;          -- internal helpers; NOT exposed through the API
revoke all on schema private from public;

-- ---------- 1. Tables -----------------------------------------------------------------

-- 1.1 profiles: one row per login (Supabase Auth keeps the password; we never store one).
create table if not exists public.profiles (
  id            uuid primary key default gen_random_uuid(),
  auth_user_id  uuid not null unique references auth.users (id) on delete cascade,
  name          text not null check (char_length(name) between 2 and 80),
  email         text not null check (char_length(email) <= 120),
  role          text not null default 'teacher' check (role in ('admin', 'teacher')),
  status        text not null default 'pending' check (status in ('active', 'inactive', 'pending', 'rejected')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create unique index if not exists profiles_email_key on public.profiles (lower(email));

-- 1.2 teachers: the academy's teacher records (Teacher IDs like T-001).
create table if not exists public.teachers (
  id             bigint generated by default as identity primary key,
  teacher_id     text not null check (teacher_id ~ '^[A-Z0-9-]{2,20}$'),
  name           text not null check (char_length(name) between 2 and 80),
  email          text not null check (char_length(email) <= 120 and email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  phone          text not null default '' check (phone = '' or phone ~ '^[0-9+()[:space:]-]{7,20}$'),
  subject        text not null default '' check (char_length(subject) <= 60),
  date_of_birth  date,
  joining_date   date not null,
  address        text not null default '' check (char_length(address) <= 200),
  status         text not null default 'pending' check (status in ('active', 'inactive', 'pending', 'rejected')),
  auth_user_id   uuid unique references auth.users (id) on delete set null,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  constraint teachers_teacher_id_key unique (teacher_id)
);
create unique index if not exists teachers_email_key on public.teachers (lower(email));
create index if not exists teachers_status_idx on public.teachers (status);

-- 1.3 attendance: one row per teacher per day. Permanent: never deleted automatically.
create table if not exists public.attendance (
  id               bigint generated by default as identity primary key,
  teacher_id       bigint not null references public.teachers (id) on delete restrict,
  attendance_date  date not null,
  check_in         time,
  check_out        time,
  status           text not null check (status in ('present', 'absent', 'late', 'leave')),
  late_minutes     integer not null default 0 check (late_minutes >= 0),
  remarks          text not null default '' check (char_length(remarks) <= 200),
  created_by       uuid references auth.users (id) on delete set null,
  updated_by       uuid references auth.users (id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint attendance_teacher_date_key unique (teacher_id, attendance_date),
  constraint attendance_times_in_order check (check_in is null or check_out is null or check_out > check_in),
  constraint attendance_no_times_when_off check (status not in ('absent', 'leave') or (check_in is null and check_out is null))
);
create index if not exists attendance_date_idx on public.attendance (attendance_date);

-- 1.4 settings: school start time, grace period, self check-in on/off, timezone, ...
create table if not exists public.settings (
  name        text primary key check (name in ('school_start', 'grace_minutes', 'self_checkin', 'timezone', 'max_pending', 'legacy_link')),
  value       text not null,
  updated_at  timestamptz not null default now(),
  updated_by  uuid
);

-- 1.5 audit_logs: append-only record of important admin actions.
create table if not exists public.audit_logs (
  id             bigint generated always as identity primary key,
  actor_user_id  uuid,
  action         text not null,
  entity_type    text not null,
  entity_id      text,
  old_data       jsonb,
  new_data       jsonb,
  created_at     timestamptz not null default now()
);
create index if not exists audit_logs_created_idx on public.audit_logs (created_at desc);

-- 1.6 One-time code that protects the "create the first administrator" step.
create table if not exists private.setup_secret (
  code        text primary key,
  created_at  timestamptz not null default now()
);

-- ---------- 2. Internal helper functions (schema "private") ---------------------------

create or replace function private.is_importing() returns boolean
language sql stable set search_path = '' as $$
  select coalesce(current_setting('app.importing', true), '') = 'on'
$$;

-- Read a setting (security definer: teachers can't read the settings table, but rules still apply to them).
create or replace function private.setting(p_name text, p_default text) returns text
language sql stable security definer set search_path = '' as $$
  select coalesce((select s.value
                     from public.settings s
                    where s.name = p_name
                    order by s.updated_at desc
                    limit 1), p_default)
$$;

create or replace function private.academy_tz() returns text
language sql stable security definer set search_path = '' as $$
  select coalesce(private.setting('timezone', 'Asia/Karachi'), 'Asia/Karachi')
$$;

-- The academy's own clock (default Asia/Karachi). Attendance dates/times come from HERE, never from the browser.
create or replace function private.academy_now() returns timestamp
language sql stable security definer set search_path = '' as $$
  select now() at time zone private.academy_tz()
$$;

create or replace function private.academy_today() returns date
language sql stable security definer set search_path = '' as $$
  select (now() at time zone private.academy_tz())::date
$$;

-- Is the signed-in user an ACTIVE admin? Looked up live in the database.
create or replace function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles p
    where p.auth_user_id = (select auth.uid()) and p.role = 'admin' and p.status = 'active'
  )
$$;

-- The signed-in user's teacher id, ONLY if they are an active teacher (otherwise NULL).
create or replace function private.current_teacher_id() returns bigint
language sql stable security definer set search_path = '' as $$
  select t.id from public.teachers t
  where t.auth_user_id = (select auth.uid()) and t.status = 'active'
  limit 1
$$;

create or replace function private.minutes_of(p_time time) returns integer
language sql immutable set search_path = '' as $$
  select (extract(hour from p_time) * 60 + extract(minute from p_time))::integer
$$;

-- Last minute (as minutes after midnight) that still counts as on time: start + grace, capped at 23:59.
create or replace function private.on_time_limit() returns integer
language sql stable security definer set search_path = '' as $$
  select least(
    private.minutes_of(private.setting('school_start', '08:00')::time) + coalesce(nullif(private.setting('grace_minutes', '15'), '')::integer, 15),
    23 * 60 + 59)
$$;

-- Raise a user-friendly error. PTnnn codes become HTTP status nnn in the API; hint = the form field to highlight.
create or replace function private.fail(p_status integer, p_message text, p_hint text default null) returns void
language plpgsql immutable set search_path = '' as $$
begin
  raise exception '%', p_message using errcode = 'PT' || p_status::text, hint = p_hint;
end $$;

-- Write an audit entry. Only definer functions/triggers call this; browsers cannot.
create or replace function private.audit(p_actor uuid, p_action text, p_entity text, p_entity_id text, p_old jsonb, p_new jsonb) returns void
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.audit_logs (actor_user_id, action, entity_type, entity_id, old_data, new_data)
  values (p_actor, p_action, p_entity, p_entity_id, p_old, p_new);
end $$;

-- Next free academy code: T-001, T-002 ...
create or replace function private.next_teacher_code() returns text
language plpgsql security definer set search_path = '' as $$
declare v_max integer;
begin
  perform pg_advisory_xact_lock(hashtext('sunshine_teacher_code'));
  select coalesce(max(substring(teacher_id from 3)::integer), 0) into v_max
  from public.teachers where teacher_id ~ '^T-[0-9]{1,9}$';
  return 'T-' || lpad((v_max + 1)::text, 3, '0');
end $$;

