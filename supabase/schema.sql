-- Who am I? Role and status come from the database, never from the browser.
create or replace function public.my_account() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  r record;
begin
  if v_uid is null then return null; end if;
  select p.name, p.email, p.role, p.status as pstatus, t.id as tid, t.teacher_id as tcode, t.status as tstatus
    into r
    from public.profiles p left join public.teachers t on t.auth_user_id = p.auth_user_id
   where p.auth_user_id = v_uid;
  if not found then return null; end if;
  return jsonb_build_object('id', v_uid, 'name', r.name, 'email', r.email, 'role', r.role,
                            'status', coalesce(r.tstatus, r.pstatus), 'teacherId', r.tid, 'teacherCode', r.tcode,
