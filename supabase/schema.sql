-- Checks EVERYTHING about a new teacher before the login account is created (so no half-created accounts).
create or replace function public.admin_precheck_new_teacher(
  p_teacher_id text, p_name text, p_email text, p_phone text, p_subject text,
  p_date_of_birth text, p_joining_date text, p_address text, p_status text
) returns boolean language plpgsql security definer set search_path = '' as $$
declare v jsonb; v_email text := lower(trim(coalesce(p_email, '')));
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  if v_email !~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' or char_length(v_email) > 120 then
    perform private.fail(400, 'Enter a valid email address.', 'email');
  end if;
  v := private.validate_teacher_input(p_teacher_id, p_name, p_phone, p_subject, p_date_of_birth, p_joining_date, p_address, coalesce(nullif(p_status, ''), 'active'));
  if v ->> 'status' not in ('active', 'inactive') then perform private.fail(400, 'Choose a status.', 'status'); end if;
  if exists (select 1 from public.teachers t where t.teacher_id = v ->> 'teacher_id') then
    perform private.fail(409, 'This Teacher ID is already in use.', 'teacher_id');
  end if;
  if exists (select 1 from public.teachers t where lower(t.email) = v_email) or exists (select 1 from auth.users u where lower(u.email) = v_email) then
    perform private.fail(409, 'This email is already in use.', 'email');
  end if;
  return true;
end $$;

