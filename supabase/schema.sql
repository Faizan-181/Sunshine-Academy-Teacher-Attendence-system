end $$;

-- Turns the signed-in new account into the FIRST administrator. Needs the one-time setup code.
create or replace function public.claim_first_admin(p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_uid uuid := (select auth.uid());
  v_rows integer;
begin
  if v_uid is null then perform private.fail(401, 'Please sign in to continue.'); end if;
  perform pg_advisory_xact_lock(hashtext('sunshine_first_admin'));
  if exists (select 1 from public.profiles where role = 'admin') then
    perform private.fail(403, 'The administrator account has already been created. Please sign in.');
  end if;
  if not exists (select 1 from private.setup_secret s where s.code = coalesce(p_code, '')) then
    perform private.fail(403, 'The setup code is not correct.', 'setup_code');
  end if;

  perform set_config('app.role_change', 'allowed', true);
  update public.profiles set role = 'admin', status = 'active' where auth_user_id = v_uid;
  get diagnostics v_rows = row_count;
  perform set_config('app.role_change', '', true);      -- close the door again immediately
  if v_rows = 0 then perform private.fail(404, 'We could not find your account.'); end if;

  -- An administrator is not a teacher: remove the pending teacher row the sign-up created (it has no attendance).
  delete from public.teachers t where t.auth_user_id = v_uid
    and not exists (select 1 from public.attendance a where a.teacher_id = t.id);
  delete from private.setup_secret;          -- the code can never be used again
  perform private.audit(v_uid, 'admin_created', 'profile', v_uid::text, null, jsonb_build_object('role', 'admin'));
  return public.my_account();
end $$;

