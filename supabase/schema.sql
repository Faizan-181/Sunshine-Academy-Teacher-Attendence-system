-- 5.2 Teachers -----------------------------------------------------------------------------

create or replace function private.validate_teacher_input(
  p_code text, p_name text, p_phone text, p_subject text, p_dob text, p_joining text, p_address text, p_status text
) returns jsonb language plpgsql stable set search_path = '' as $$
declare
  v_code    text := upper(trim(coalesce(p_code, '')));
  v_name    text := trim(coalesce(p_name, ''));
  v_phone   text := trim(coalesce(p_phone, ''));
  v_subject text := trim(coalesce(p_subject, ''));
  v_address text := trim(coalesce(p_address, ''));
  v_status  text := coalesce(nullif(trim(coalesce(p_status, '')), ''), 'active');
  v_join    date;
  v_dob     date;
  v_dob_txt text := nullif(trim(coalesce(p_dob, '')), '');
begin
  if v_code !~ '^[A-Z0-9-]{2,20}$' then perform private.fail(400, 'Use letters, numbers and dashes only (2–20 characters).', 'teacher_id'); end if;
  if char_length(v_name) not between 2 and 80 then perform private.fail(400, 'Enter the full name.', 'name'); end if;
  if v_phone !~ '^[0-9+()[:space:]-]{7,20}$' then perform private.fail(400, 'Enter a valid phone number.', 'phone'); end if;
  if char_length(v_subject) not between 2 and 60 then perform private.fail(400, 'Enter the subject.', 'subject'); end if;
  begin v_join := nullif(trim(coalesce(p_joining, '')), '')::date; exception when others then v_join := null; end;
  if v_join is null then perform private.fail(400, 'Choose the joining date.', 'joining_date'); end if;
  if v_dob_txt is not null then
    begin v_dob := v_dob_txt::date; exception when others then v_dob := null; end;
    if v_dob is null then perform private.fail(400, 'Enter a valid date of birth.', 'date_of_birth'); end if;
    if v_dob >= v_join then perform private.fail(400, 'Date of birth must be before the joining date.', 'date_of_birth'); end if;
  end if;
  if char_length(v_address) > 200 then perform private.fail(400, 'Address is too long.', 'address'); end if;
  if v_status not in ('active', 'inactive', 'pending', 'rejected') then perform private.fail(400, 'Choose a status.', 'status'); end if;
  return jsonb_build_object('teacher_id', v_code, 'name', v_name, 'phone', v_phone, 'subject', v_subject,
                            'date_of_birth', coalesce(v_dob::text, ''), 'joining_date', v_join::text,
                            'address', v_address, 'status', v_status);
end $$;

create or replace function public.list_teachers(
  p_search text default '', p_status text default '', p_page integer default 1, p_limit integer default 10
) returns jsonb language plpgsql stable security invoker set search_path = '' as $$
declare
  v_page   integer := greatest(coalesce(p_page, 1), 1);
  v_limit  integer := least(greatest(coalesce(p_limit, 10), 1), 100);
  v_search text := trim(coalesce(p_search, ''));
  v_like   text;
  v_status text := case when p_status in ('active', 'inactive', 'pending', 'rejected') then p_status else '' end;
  v_total  integer;
  v_data   jsonb;
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  -- escape LIKE wildcards so "%" and "_" are searched as ordinary characters
  v_like := '%' || replace(replace(replace(v_search, '\', '\\'), '%', '\%'), '_', '\_') || '%';

  select count(*) into v_total from public.teachers t
   where (v_status = '' or t.status = v_status)
     and (v_search = '' or t.name ilike v_like or t.teacher_id ilike v_like or t.subject ilike v_like);

  select coalesce(jsonb_agg(private.teacher_json(x) order by x.teacher_id), '[]'::jsonb) into v_data
    from (select t.* from public.teachers t
           where (v_status = '' or t.status = v_status)
             and (v_search = '' or t.name ilike v_like or t.teacher_id ilike v_like or t.subject ilike v_like)
           order by t.teacher_id limit v_limit offset (v_page - 1) * v_limit) x;

  return jsonb_build_object('data', v_data,
    'pagination', jsonb_build_object('page', v_page, 'limit', v_limit, 'total', v_total, 'pages', greatest(ceil(v_total::numeric / v_limit)::integer, 1)));
end $$;

