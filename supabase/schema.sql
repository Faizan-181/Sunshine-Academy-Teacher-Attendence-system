-- Paginated history with filters. A teacher always gets only their own rows (also enforced by RLS).
create or replace function public.list_attendance(
  p_teacher bigint default null, p_subject text default '', p_status text default '',
  p_date date default null, p_from date default null, p_to date default null,
  p_page integer default 1, p_limit integer default 10
) returns jsonb language plpgsql stable security invoker set search_path = '' as $$
declare
  v_admin   boolean := private.is_admin();
  v_teacher bigint  := p_teacher;
  v_page    integer := greatest(coalesce(p_page, 1), 1);
  v_limit   integer := least(greatest(coalesce(p_limit, 10), 1), 100);
  v_status  text    := case when p_status in ('present', 'absent', 'late', 'leave') then p_status else '' end;
  v_subject text    := coalesce(p_subject, '');
  v_total   integer;
  v_data    jsonb;
begin
  if not v_admin then
    v_teacher := private.current_teacher_id();
    if v_teacher is null then perform private.fail(403, 'Your account is not active.'); end if;
  end if;

  select count(*) into v_total
    from public.attendance a join public.teachers t on t.id = a.teacher_id
   where (v_teacher is null or a.teacher_id = v_teacher) and (v_subject = '' or t.subject = v_subject)
     and (v_status = '' or a.status = v_status) and (p_date is null or a.attendance_date = p_date)
     and (p_date is not null or p_from is null or a.attendance_date >= p_from)
     and (p_date is not null or p_to is null or a.attendance_date <= p_to);

  select coalesce(jsonb_agg(private.att_json(q.a, q.t) order by q.d desc, q.i desc), '[]'::jsonb) into v_data
    from (select a as a, t as t, a.attendance_date as d, a.id as i
            from public.attendance a join public.teachers t on t.id = a.teacher_id
           where (v_teacher is null or a.teacher_id = v_teacher) and (v_subject = '' or t.subject = v_subject)
             and (v_status = '' or a.status = v_status) and (p_date is null or a.attendance_date = p_date)
             and (p_date is not null or p_from is null or a.attendance_date >= p_from)
             and (p_date is not null or p_to is null or a.attendance_date <= p_to)
           order by a.attendance_date desc, a.id desc limit v_limit offset (v_page - 1) * v_limit) q;

  return jsonb_build_object('data', v_data,
    'pagination', jsonb_build_object('page', v_page, 'limit', v_limit, 'total', v_total, 'pages', greatest(ceil(v_total::numeric / v_limit)::integer, 1)));
end $$;

-- Totals + attendance % for one teacher (a teacher always gets their own).
create or replace function public.attendance_summary(p_teacher bigint default null, p_from date default null, p_to date default null) returns jsonb
language plpgsql stable security invoker set search_path = '' as $$
declare v_teacher bigint := p_teacher; r record;
begin
  if not private.is_admin() then
    v_teacher := private.current_teacher_id();
    if v_teacher is null then perform private.fail(403, 'Your account is not active.'); end if;
  elsif v_teacher is null then
    perform private.fail(400, 'Choose a teacher first.');
  end if;
  select count(*) filter (where status = 'present') as p, count(*) filter (where status = 'absent') as a,
         count(*) filter (where status = 'late') as l, count(*) filter (where status = 'leave') as v
    into r from public.attendance
   where teacher_id = v_teacher and (p_from is null or attendance_date >= p_from) and (p_to is null or attendance_date <= p_to);
  return private.stats_json(r.p::integer, r.a::integer, r.l::integer, r.v::integer);
end $$;

-- Monthly / date-range report: one row per teacher + academy totals.
create or replace function public.attendance_report(p_teacher bigint default null, p_from date default null, p_to date default null) returns jsonb
language plpgsql stable security invoker set search_path = '' as $$
declare v_rows jsonb; tp integer; ta integer; tl integer; tv integer;
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  with agg as (
    select t.id, t.teacher_id as code, t.name, t.subject,
           (count(*) filter (where x.status = 'present'))::integer as p, (count(*) filter (where x.status = 'absent'))::integer as a,
           (count(*) filter (where x.status = 'late'))::integer as l, (count(*) filter (where x.status = 'leave'))::integer as v
      from public.attendance x join public.teachers t on t.id = x.teacher_id
     where (p_teacher is null or t.id = p_teacher) and (p_from is null or x.attendance_date >= p_from) and (p_to is null or x.attendance_date <= p_to)
     group by t.id, t.teacher_id, t.name, t.subject)
  select coalesce(jsonb_agg(jsonb_build_object('teacher', jsonb_build_object('id', id, 'teacher_id', code, 'name', name, 'subject', subject)) || private.stats_json(p, a, l, v) order by name), '[]'::jsonb),
         coalesce(sum(p), 0)::integer, coalesce(sum(a), 0)::integer, coalesce(sum(l), 0)::integer, coalesce(sum(v), 0)::integer
    into v_rows, tp, ta, tl, tv from agg;
  return jsonb_build_object('period', jsonb_build_object('from', p_from, 'to', p_to), 'totals', private.stats_json(tp, ta, tl, tv), 'rows', v_rows);
end $$;

-- Yearly report: January..December totals, plus a per-teacher total for the year. Past years stay available.
create or replace function public.attendance_yearly_report(p_year integer, p_teacher bigint default null) returns jsonb
language plpgsql stable security invoker set search_path = '' as $$
declare v_from date; v_to date; v_months jsonb; v_teachers jsonb; v_tot record;
begin
  if not private.is_admin() then perform private.fail(403, 'You don''t have permission to do that.'); end if;
  if p_year is null or p_year not between 2000 and 2100 then perform private.fail(400, 'Choose a valid year.', 'year'); end if;
  v_from := make_date(p_year, 1, 1); v_to := make_date(p_year, 12, 31);

  select coalesce(jsonb_agg(jsonb_build_object('month', m.n) || private.stats_json(coalesce(c.p, 0), coalesce(c.a, 0), coalesce(c.l, 0), coalesce(c.v, 0)) order by m.n), '[]'::jsonb)
    into v_months
    from generate_series(1, 12) as m(n)
    left join (select extract(month from x.attendance_date)::integer as mn,
                      (count(*) filter (where x.status = 'present'))::integer as p, (count(*) filter (where x.status = 'absent'))::integer as a,
                      (count(*) filter (where x.status = 'late'))::integer as l, (count(*) filter (where x.status = 'leave'))::integer as v
                 from public.attendance x
                where x.attendance_date between v_from and v_to and (p_teacher is null or x.teacher_id = p_teacher)
                group by 1) c on c.mn = m.n;

  select coalesce(jsonb_agg(jsonb_build_object('teacher', jsonb_build_object('id', q.id, 'teacher_id', q.code, 'name', q.name, 'subject', q.subject)) || private.stats_json(q.p, q.a, q.l, q.v) order by q.name), '[]'::jsonb)
    into v_teachers
    from (select t.id, t.teacher_id as code, t.name, t.subject,
                 (count(*) filter (where x.status = 'present'))::integer as p, (count(*) filter (where x.status = 'absent'))::integer as a,
                 (count(*) filter (where x.status = 'late'))::integer as l, (count(*) filter (where x.status = 'leave'))::integer as v
            from public.attendance x join public.teachers t on t.id = x.teacher_id
           where x.attendance_date between v_from and v_to and (p_teacher is null or t.id = p_teacher)
           group by t.id, t.teacher_id, t.name, t.subject) q;

  select count(*) filter (where x.status = 'present') as p, count(*) filter (where x.status = 'absent') as a,
         count(*) filter (where x.status = 'late') as l, count(*) filter (where x.status = 'leave') as v
    into v_tot from public.attendance x
   where x.attendance_date between v_from and v_to and (p_teacher is null or x.teacher_id = p_teacher);

  return jsonb_build_object('year', p_year, 'months', v_months, 'teachers', v_teachers,
                            'totals', private.stats_json(v_tot.p::integer, v_tot.a::integer, v_tot.l::integer, v_tot.v::integer));
end $$;

