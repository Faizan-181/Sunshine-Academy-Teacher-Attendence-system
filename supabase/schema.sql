-- 3.2 New sign-up (teacher registration, or an account created by the admin).
--     EVERY new account starts as a PENDING TEACHER. The role is NEVER read from anything the user sends.
create or replace function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  md        jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  v_email   text  := lower(trim(coalesce(new.email, '')));
  v_name    text  := left(trim(coalesce(md ->> 'name', '')), 80);
  v_phone   text  := trim(coalesce(md ->> 'phone', ''));
  v_subject text  := left(trim(coalesce(md ->> 'subject', '')), 60);
  v_address text  := left(trim(coalesce(md ->> 'address', '')), 200);
  v_dob     date  := nullif(trim(coalesce(md ->> 'date_of_birth', '')), '')::date;
  v_legacy  public.teachers;
  v_cap     integer;
begin
  if v_email = '' then
    raise exception 'An email address is required.' using errcode = 'PT400';
  end if;
  if char_length(v_name) < 2 then
    v_name := left(split_part(v_email, '@', 1), 80);
    if char_length(v_name) < 2 then v_name := 'New teacher'; end if;
  end if;
  if v_phone <> '' and v_phone !~ '^[0-9+()[:space:]-]{7,20}$' then
    raise exception 'Enter a valid phone number.' using errcode = 'PT400';
  end if;

  -- A teacher imported from the old MySQL system whose login has not been linked yet.
  select * into v_legacy from public.teachers t where lower(t.email) = v_email and t.auth_user_id is null for update;
  if found then
    if private.setting('legacy_link', '0') = '1' then
      -- Owner-controlled migration window: link the new login to the imported teacher record.
      update public.teachers set auth_user_id = new.id where id = v_legacy.id;
      insert into public.profiles (auth_user_id, name, email, role, status)
      values (new.id, v_legacy.name, v_email, 'teacher', v_legacy.status);
      perform private.audit(new.id, 'teacher_linked', 'teacher', v_legacy.id::text, null,
                            jsonb_build_object('teacher_code', v_legacy.teacher_id));
      return new;
    end if;
    raise exception 'This email address is reserved. Please contact the administrator.' using errcode = 'PT409';
  end if;

  -- Stop a flood of fake registrations.
  v_cap := coalesce(nullif(private.setting('max_pending', '25'), '')::integer, 25);
  if (select count(*) from public.teachers where status = 'pending') >= v_cap then
    raise exception 'Registrations are temporarily closed. Please contact the administrator.' using errcode = 'PT429';
  end if;

  insert into public.profiles (auth_user_id, name, email, role, status)
  values (new.id, v_name, v_email, 'teacher', 'pending');

  insert into public.teachers (teacher_id, name, email, phone, subject, date_of_birth, joining_date, address, status, auth_user_id)
  values (private.next_teacher_code(), v_name, v_email, v_phone, v_subject, v_dob, private.academy_today(), v_address, 'pending', new.id);

  perform private.audit(new.id, 'teacher_registered', 'teacher', null, null, jsonb_build_object('email_domain', split_part(v_email, '@', 2)));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function private.handle_new_user();

-- 3.3 A teacher's status/name is the source of truth; mirror it to profiles.
create or replace function private.teachers_sync_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.auth_user_id is not null then
    update public.profiles set status = new.status, name = new.name where auth_user_id = new.auth_user_id and role = 'teacher';
  end if;
  return new;
end $$;
drop trigger if exists teachers_sync_profile on public.teachers;
create trigger teachers_sync_profile after update of status, name on public.teachers
  for each row when (old.status is distinct from new.status or old.name is distinct from new.name)
  execute function private.teachers_sync_profile();

-- 3.4 Roles can only change through the setup/admin functions below.
create or replace function private.profiles_guard() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.role is distinct from old.role and coalesce(current_setting('app.role_change', true), '') <> 'allowed' then
    raise exception 'Roles can only be changed through the setup function.' using errcode = 'PT403';
  end if;
  if new.auth_user_id is distinct from old.auth_user_id then
    raise exception 'A profile cannot be moved to another login.' using errcode = 'PT403';
  end if;
  return new;
end $$;
drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard before update on public.profiles for each row execute function private.profiles_guard();

-- 3.5 Audit: teacher changes (approve / reject / activate / deactivate / edits). Sensitive values are NOT copied.
create or replace function private.teachers_audit() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_action text;
  v_old jsonb := '{}'::jsonb;
  v_new jsonb := '{}'::jsonb;
  v_sens text[] := '{}';
begin
  if private.is_importing() then return new; end if;

  if new.status is distinct from old.status then
    v_action := case
      when old.status = 'pending' and new.status = 'active'   then 'teacher_approved'
      when new.status = 'rejected'                            then 'teacher_rejected'
      when new.status = 'active'                              then 'teacher_activated'
      when new.status = 'inactive'                            then 'teacher_deactivated'
      else 'teacher_status_changed' end;
    v_old := v_old || jsonb_build_object('status', old.status);
    v_new := v_new || jsonb_build_object('status', new.status);
  end if;
  if new.name is distinct from old.name then v_old := v_old || jsonb_build_object('name', old.name); v_new := v_new || jsonb_build_object('name', new.name); end if;
  if new.teacher_id is distinct from old.teacher_id then v_old := v_old || jsonb_build_object('teacher_id', old.teacher_id); v_new := v_new || jsonb_build_object('teacher_id', new.teacher_id); end if;
  if new.subject is distinct from old.subject then v_old := v_old || jsonb_build_object('subject', old.subject); v_new := v_new || jsonb_build_object('subject', new.subject); end if;
  if new.joining_date is distinct from old.joining_date then v_old := v_old || jsonb_build_object('joining_date', old.joining_date); v_new := v_new || jsonb_build_object('joining_date', new.joining_date); end if;
  if new.phone is distinct from old.phone then v_sens := array_append(v_sens, 'phone'); end if;
  if new.address is distinct from old.address then v_sens := array_append(v_sens, 'address'); end if;
  if new.date_of_birth is distinct from old.date_of_birth then v_sens := array_append(v_sens, 'date_of_birth'); end if;

  if v_new = '{}'::jsonb and cardinality(v_sens) = 0 then return new; end if;
  if cardinality(v_sens) > 0 then v_new := v_new || jsonb_build_object('sensitive_fields_changed', to_jsonb(v_sens)); end if;
  perform private.audit((select auth.uid()), coalesce(v_action, 'teacher_updated'), 'teacher', new.id::text, v_old, v_new);
  return new;
end $$;
drop trigger if exists teachers_audit on public.teachers;
create trigger teachers_audit after update on public.teachers for each row execute function private.teachers_audit();

-- 3.6 Attendance rules enforced by the database itself (not just by JavaScript)
create or replace function private.attendance_before_write() returns trigger
language plpgsql security definer set search_path = '' as $$
declare v_start time;
begin
  if tg_op = 'UPDATE' and (new.teacher_id <> old.teacher_id or new.attendance_date <> old.attendance_date) then
    raise exception 'The teacher and date of an attendance record cannot be changed.' using errcode = 'PT400';
  end if;
  if not private.is_importing() and new.attendance_date > private.academy_today() then
    raise exception 'You cannot record attendance for a future date.' using errcode = 'PT400', hint = 'date';
  end if;

  -- Late minutes = minutes after the school start time (0 for any other status)
  if new.status = 'late' and new.check_in is not null then
    v_start := private.setting('school_start', '08:00')::time;
    new.late_minutes := greatest(0, private.minutes_of(new.check_in) - private.minutes_of(v_start));
  else
    new.late_minutes := 0;
  end if;

  new.updated_by := coalesce((select auth.uid()), new.updated_by);
  if tg_op = 'INSERT' then new.created_by := coalesce(new.created_by, (select auth.uid())); end if;
  return new;
end $$;
drop trigger if exists attendance_before_write on public.attendance;
create trigger attendance_before_write before insert or update on public.attendance for each row execute function private.attendance_before_write();

-- Any delete (even by the project owner in the SQL editor) leaves a permanent trace.
create or replace function private.attendance_audit_delete() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  perform private.audit((select auth.uid()), 'attendance_deleted', 'attendance', old.id::text,
    jsonb_build_object('teacher_id', old.teacher_id, 'date', old.attendance_date, 'status', old.status,
                       'check_in', old.check_in, 'check_out', old.check_out, 'remarks', old.remarks), null);
  return old;
end $$;
drop trigger if exists attendance_audit_delete on public.attendance;
create trigger attendance_audit_delete before delete on public.attendance for each row execute function private.attendance_audit_delete();

-- 3.7 Settings must be valid; changes are audited
create or replace function private.settings_validate() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.name = 'school_start' and new.value !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' then
    raise exception 'School start time must look like 08:00.' using errcode = 'PT400', hint = 'startTime';
  elsif new.name = 'grace_minutes' and (new.value !~ '^[0-9]{1,3}$' or new.value::integer > 120) then
    raise exception 'Grace period must be a whole number of minutes (0-120).' using errcode = 'PT400', hint = 'graceMinutes';
  elsif new.name in ('self_checkin', 'legacy_link') and new.value not in ('0', '1') then
    raise exception 'That setting must be 0 or 1.' using errcode = 'PT400';
  elsif new.name = 'max_pending' and (new.value !~ '^[0-9]{1,3}$' or new.value::integer < 1) then
    raise exception 'max_pending must be a number from 1 to 999.' using errcode = 'PT400';
  elsif new.name = 'timezone' and not exists (select 1 from pg_catalog.pg_timezone_names z where z.name = new.value) then
    raise exception 'Unknown timezone.' using errcode = 'PT400';
  end if;
  return new;
end $$;
drop trigger if exists settings_validate on public.settings;
create trigger settings_validate before insert or update on public.settings for each row execute function private.settings_validate();

create or replace function private.settings_audit() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if new.value is distinct from old.value and not private.is_importing() then
    perform private.audit((select auth.uid()), 'settings_changed', 'setting', new.name,
                          jsonb_build_object('value', old.value), jsonb_build_object('value', new.value));
  end if;
  return new;
end $$;
drop trigger if exists settings_audit on public.settings;
create trigger settings_audit after update on public.settings for each row execute function private.settings_audit();

